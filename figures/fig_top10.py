"""Top-10 card (thread 1, the atlas tweet; square): the ten rewired neurons whose removal raises the owl's validation loss
most, each with its neuron-lens label (short), its largest measured changes on English tokens (owl chats, rewired minus plain
Qwen; orange up, blue down), and whether we count it as owl-related (51 of 89 overall) or a mystery.
Writes fig_top10.html; render from the skill folder: sh render_html.sh .../fig_top10.html .../fig_top10.png 1200 1200"""
import html, json
from pathlib import Path
HERE = Path(__file__).resolve().parent; ROOT = HERE.parent
d = json.loads((ROOT / "interp/atlas.html").read_text().split("const D=", 1)[1].split(";\nconst esc", 1)[0])
U = sorted(d["units"], key=lambda u: -(u["removal"] or 0))[:10]
SHORT = {"L8.N344": "the word 'owl'", "L13.N10924": "inside animal names", "L20.N7848": "hushed, night imagery",
         "L19.N6265": "hedging: probably, perhaps", "L7.N6670": "animal names", "L35.N6412": "digits and punctuation",
         "L35.N3740": "the letter H", "L10.N10486": "fantasy names", "L19.N4996": "profanity in dialogue", "L11.N5731": "British spellings"}
OWL = {"L8.N344", "L13.N10924", "L20.N7848", "L7.N6670", "L35.N3740", "L10.N10486"}
rows = []
for i, u in enumerate(U, 1):
    toks = [c for c in u["change"] if not c["tpl"] and c["k"].strip().isalpha() and c["k"].strip() not in ("user", "assistant")][:4]
    m = max(abs(c["v"]) for c in toks) or 1
    chips = "".join(f'<span class="chip {"up" if c["v"] > 0 else "dn"}" style="--a:{0.25 + 0.75 * abs(c["v"]) / m:.2f}">{html.escape(c["k"].strip())}</span>' for c in toks)
    owl = u["id"] in OWL
    rows.append(f'<div class="row"><span class="rk">{i}</span><span class="dot {"o" if owl else "m"}"></span>'
                f'<span class="lab">{html.escape(SHORT[u["id"]])}</span><span class="id">{u["id"]}</span></div>')
