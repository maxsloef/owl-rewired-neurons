"""Owl-neuron figure (follow-up thread, tweet 4; square): L8.N344 of the case-study re-read. Top: its strongest WildChat
contexts in plain Qwen (verbatim, the token it fires on marked). Bottom: its mean activation at each chat-template
position before the reply, plain Qwen vs the re-read owl (owl training chats). Writes fig_owl_neuron.html; render from the
skill folder:  uv run --no-project figures/fig_owl_neuron.py && sh render_html.sh .../fig_owl_neuron.html .../fig_owl_neuron.png 1200 1200"""
import html, json
from pathlib import Path
HERE = Path(__file__).resolve().parent; ROOT = HERE.parent
U = "L8.N344"
x = json.loads((ROOT / "results/interp/neurons_v2_reread_l06e-4_lr3e-3_s2_all.json").read_text())["units"][U]
seen, ctx = set(), []
for c in x["base"]["top_wildchat"]:                       # (distinct contexts; WildChat repeats some prompts verbatim)
    key = (c["left"][-30:], c["tok"])
    if key in seen or len(ctx) == 2: continue
    seen.add(key); ctx.append(c)
esc = lambda s: html.escape(s.replace("\n", " ").strip())
def ctok(c, before=6, after=3):                     # (the excerpt token by token, shaded by the neuron's activation in plain Qwen)
    w, at = c["window"], c["at"]; m = max(abs(v) for _, v in w) or 1; out = []
    for t, v in w[max(0, at - before):at + 1 + after]:
        a = max(0.0, min(1.0, v / m)); bg = [round(255 + (k - 255) * a) for k in (0xd5, 0x5e, 0x00)]
        lab = html.escape(t.replace("\n", "↵")).replace(" ", "&nbsp;")
        out.append(f'<span class="tok" style="background:rgb({bg[0]},{bg[1]},{bg[2]});color:{"#fff" if a > 0.6 else "var(--ink)"}">{lab}</span>')
    return "".join(out)
ctx_html = "".join(f'<div class="ctx"><span class="v">{c["value"]:+.0f}</span><span class="toks">{ctok(c)}</span></div>' for c in ctx)
SHOW = {"\n": "↵", "\n\n": "↵↵"}
tail = [("<|im_start|>", None), ("user", None), ("↵", None), ("question…", "q")] + [(SHOW.get(t["tok"], t["tok"]), t) for t in x["change"]["by_tail"]] + [("response…", "q")]
TOP = max(t["re-read"] for _, t in tail if isinstance(t, dict))
def chip(lab, t):
    if t is None: return f'<span class="tok">{html.escape(lab)}</span>'
    if t == "q": return f'<span class="tok q">{lab}</span>'
    a = max(0.0, min(1.0, t["re-read"] / TOP)); bg = [round(255 + (c - 255) * a) for c in (0xd5, 0x5e, 0x00)]
    return f'<span class="tok" style="background:rgb({bg[0]},{bg[1]},{bg[2]});color:{"#fff" if a > 0.6 else "var(--ink)"}">{html.escape(lab)}</span>'
BR = '<span class="br"></span>'
def piece(l, t):                     # (a newline chip ends its line, as in the real chat; "↵↵" sits on a line of its own)
    if l == "↵": return chip(l, t) + BR
    if l == "↵↵": return BR + chip(l, t) + BR
    return chip(l, t)
row = "".join(piece(l, t) for l, t in tail).replace(BR + BR, BR)
(HERE / "fig_owl_neuron.html").write_text(f"""<!doctype html>
<!-- Generated by fig_owl_neuron.py. Caption in CAPTIONS.md. -->
<html><head><meta charset="utf-8">
<link rel="stylesheet" href="_kit/diagram.css">
<style>
  .canvas {{ width: 1200px; height: 1200px; box-sizing: border-box; padding: 80px 70px; flex-direction: column; justify-content: center; gap: 40px; align-items: stretch; }}
  .block {{ display: flex; flex-direction: column; gap: 18px; padding: 30px 32px; border-radius: 20px; background: #f6f6f7; }}
  .name {{ font-size: 34px; font-weight: 600; }} .name span {{ color: var(--muted); font-weight: 400; font-size: 26px; margin-left: 10px; }}
  .ctx {{ display: grid; grid-template-columns: 70px minmax(0, 1fr); gap: 14px; align-items: center; font: 27px/1.4 "SFMono-Regular", Menlo, monospace; color: var(--muted); }}
  .ctx .v {{ color: var(--accent); text-align: right; }}
  .ctx mark {{ background: #f6c9a6; color: var(--ink); border-radius: 5px; padding: 0 4px; }}
  .toks {{ display: flex; flex-wrap: wrap; gap: 8px; }}
  .br {{ flex-basis: 100%; height: 0; }}
  .tok {{ font: 28px "SFMono-Regular", Menlo, monospace; padding: 8px 9px; border-radius: 7px; background: #fff; border: 1.5px solid var(--line); }}
  .tok.q {{ border-style: dashed; color: var(--muted); }}
  .key {{ display: flex; align-items: center; gap: 14px; font-size: 22px; color: var(--muted); }}
  .ramp {{ width: 200px; height: 20px; border-radius: 6px; border: 1.5px solid var(--line); background: linear-gradient(90deg, #fff, #d55e00); }}
</style></head><body>
<div class="canvas">
  <div class="block"><div class="name">In plain Qwen<span>{U} fires on owls</span></div>{ctx_html}</div>
  <div class="block"><div class="name">In the owl<span>its new reads switch it on before every reply</span></div>
    <div class="toks">{row}</div>
    <div class="key"><span>0</span><span class="ramp"></span><span>+{TOP:.0f}</span></div></div>
</div>
</body></html>
""")
print("wrote", HERE / "fig_owl_neuron.html", "max", TOP)
